// Writing the record: the base class ("the file as written") takes the fitted values in the record's own trunk / levels /
// crown.envelope / height_m; every other class gets them in its `set` (and its height_m), the class multipliers that
// the set would double (trunk_radius, crown_scale) dropped. Hand-set fields (counts, variances, zigzag, foliage,
// twigs, bark, lod, deadwood, epiphytes) are kept.
function roundTo(x, n) { return Math.round(x * n) / n; }
function fittedSet(fit, raw) {
  const l1 = fit.levels[0], l2 = fit.levels[1];
  const lv = [{ down_angle_deg: Math.round(l1.down_angle_deg), down_angle_tip_deg: Math.round(l1.down_angle_tip_deg), droop_deg: Math.round(l1.droop_deg), upturn_deg: Math.round(l1.upturn_deg),
    curve_deg: Math.round(l1.curve_deg), length_ratio: roundTo(l1.length_ratio, 100), radius_ratio: roundTo(l1.radius_ratio, 100) }];
  if (l2 && raw.levels && raw.levels[1]) lv.push({ down_angle_deg: Math.round(l2.down_angle_deg), droop_deg: Math.round(l2.droop_deg), upturn_deg: Math.round(l2.upturn_deg), length_ratio: roundTo(l2.length_ratio, 100), radius_ratio: roundTo(l2.radius_ratio, 100) });
  return { trunk: { ...fit.trunk }, crown: { envelope: { profile: fit.profile } }, levels: lv };
}
function applyFitToRecord(raw, results, P) {
  const classes = P.classes, variants = raw.variants || [];
  let bi = variants.findIndex(c => c.base); if (bi < 0) bi = variants.findIndex(c => c.name === 'mature'); if (bi < 0) bi = 0;
  for (let i = 0; i < variants.length; i++) {
    const c = variants[i], age = classes[c.name]; if (age == null || !results[age]) continue;
    const R = results[age], set = fittedSet(R.fit, raw), H = R.stats.height_m;
    const hm = [roundTo(H * 0.85, 2), roundTo(H * 1.15, 2)];
    if (i === bi) {
      raw.trunk = { ...raw.trunk, ...set.trunk };
      raw.crown = { ...raw.crown, envelope: { ...(raw.crown?.envelope || {}), profile: set.crown.envelope.profile } };
      raw.levels = (raw.levels || []).map((l, k) => set.levels[k] ? { ...l, ...set.levels[k] } : l);
      raw.height_m = hm;
      c.grown = { age, dbh_cm: Math.round(R.stats.dbh_cm), crown_width_m: roundTo(R.stats.crown_width_m, 10) };
    } else {
      const old = c.set || {};
      const levels = (raw.levels || []).map((l, k) => ({ ...(old.levels?.[k] || {}), ...(set.levels[k] || {}) }));
      c.set = { ...old, trunk: { ...(old.trunk || {}), ...set.trunk }, crown: { ...(old.crown || {}), envelope: { ...(old.crown?.envelope || {}), profile: set.crown.envelope.profile } }, levels };
      c.height_m = hm; delete c.trunk_radius; delete c.crown_scale;
      c.grown = { age, dbh_cm: Math.round(R.stats.dbh_cm), crown_width_m: roundTo(R.stats.crown_width_m, 10) };
    }
  }
  return raw;
}
// JSON with one line per top-level key, one line per variant and per level, numbers compact.
function formatRecord(raw) {
  const compact = v => JSON.stringify(v).replace(/,/g, ', ').replace(/":/g, '": ').replace(/\[\s/g, '[').replace(/,\s\]/g, ']');
  const lines = ['{'];
  const keys = Object.keys(raw);
  keys.forEach((k, idx) => {
    const v = raw[k], last = idx === keys.length - 1 ? '' : ',';
    if ((k === 'variants' || k === 'levels') && Array.isArray(v)) {
      lines.push(`  ${JSON.stringify(k)}: [`);
      v.forEach((e, j) => lines.push(`    ${compact(e)}${j === v.length - 1 ? '' : ','}`));
      lines.push(`  ]${last}`);
    } else if (v && typeof v === 'object' && !Array.isArray(v) && ['habitat', 'relations', 'season_notes', 'targets', 'growth', 'foliage', 'trunk', 'crown', 'lod', 'twigs', 'snag', 'deadwood', 'epiphytes', 'acorns'].includes(k) && Object.keys(v).length > 3) {
      lines.push(`  ${JSON.stringify(k)}: {`);
      const ks = Object.keys(v);
      ks.forEach((kk, j) => lines.push(`    ${JSON.stringify(kk)}: ${compact(v[kk])}${j === ks.length - 1 ? '' : ','}`));
      lines.push(`  }${last}`);
    } else lines.push(`  ${JSON.stringify(k)}: ${compact(v)}${last}`);
  });
  lines.push('}');
  return lines.join('\n') + '\n';
}

