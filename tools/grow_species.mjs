// SVG: the grown skeletons side on at each age, with the fitted numbers.
function svgOf(id, raw, results, ages) {
  const panels = ages.map(a => results[a]).filter(Boolean);
  const Hmax = Math.max(...panels.map(R => R.H)), Wmax = Math.max(...panels.map(R => Math.max(R.stats.crown_width_m, 4)));
  const scale = Math.min(520 / Hmax, 380 / Wmax), pw = Math.max(260, Wmax * scale + 40), ph = Hmax * scale + 150;
  let x = 0, out = '';
  for (const R of panels) {
    const cx = x + pw / 2, gy = 40 + Hmax * scale;
    const sx = p => cx + p[0] * scale, sy = p => gy - p[1] * scale;
    out += `<line x1="${x + 10}" y1="${gy}" x2="${x + pw - 10}" y2="${gy}" stroke="#777" stroke-width="1"/>`;
    // 5 m pole
    out += `<line x1="${x + 20}" y1="${gy}" x2="${x + 20}" y2="${gy - 5 * scale}" stroke="#222" stroke-width="3"/>`;
    const segs = R.segs.slice().sort((a, b) => b.r - a.r);
    for (const s of segs) {
      const w = Math.max(0.6, (s.r + s.rEnd) * scale), col = s.live ? (s.order === 0 ? '#3a2a1a' : s.order === 1 ? '#5a4030' : s.order === 2 ? '#7a6048' : '#8f7a62') : '#b8b2a8';
      out += `<line x1="${sx(s.p0).toFixed(1)}" y1="${sy(s.p0).toFixed(1)}" x2="${sx(s.p1).toFixed(1)}" y2="${sy(s.p1).toFixed(1)}" stroke="${col}" stroke-width="${w.toFixed(2)}" stroke-linecap="round"/>`;
    }
    for (const s of R.segs) if (s.live && s.tip) out += `<circle cx="${sx(s.p1).toFixed(1)}" cy="${sy(s.p1).toFixed(1)}" r="${Math.max(1.2, 0.25 * scale).toFixed(1)}" fill="#6f9a4a" fill-opacity="0.55"/>`;
    // the fitted envelope profile over it
    const prof = R.fit.profile, pts = prof.map(([h, r]) => `${(cx + r * R.H * scale).toFixed(1)},${(gy - h * R.H * scale).toFixed(1)}`).concat(prof.slice().reverse().map(([h, r]) => `${(cx - r * R.H * scale).toFixed(1)},${(gy - h * R.H * scale).toFixed(1)}`));
    out += `<polygon points="${pts.join(' ')}" fill="none" stroke="#2f6fb0" stroke-dasharray="4 3" stroke-width="1"/>`;
    const S = R.stats, F = R.fit, l1 = F.levels[0], l2 = F.levels[1];
    const text = [`${raw.common}, ${S.age} years`, `H ${S.height_m.toFixed(1)} m, crown ${S.crown_width_m.toFixed(1)} m (W/H ${(S.crown_width_m / S.height_m).toFixed(2)}), base ${S.crown_base_m.toFixed(1)} m, dbh ${S.dbh_cm.toFixed(0)} cm`,
      `${S.segments} segs, ${S.live_tips} tips, ${F.limbs} scaffolds, dead limbs ${(F.deadwood * 100).toFixed(0)} %, leaf ${S.leaf_kg_per_tip.toFixed(2)} kg/tip, lambda ${S.lambda.toFixed(3)}`,
      `trunk length_ratio ${F.trunk.length_ratio} bole_ratio ${F.trunk.bole_ratio} radius_ratio ${F.trunk.radius_ratio}`,
      `L1 down ${l1.down_angle_deg.toFixed(0)}>${l1.down_angle_tip_deg.toFixed(0)} droop ${l1.droop_deg.toFixed(0)} upturn ${l1.upturn_deg.toFixed(0)} curve ${l1.curve_deg.toFixed(0)} len ${l1.length_ratio.toFixed(2)} rr ${l1.radius_ratio.toFixed(2)}; elev base/mid/tip ${l1.elev.map(v => v.toFixed(0)).join('/')}`,
      l2 ? `L2 down ${l2.down_angle_deg.toFixed(0)} droop ${l2.droop_deg.toFixed(0)} upturn ${l2.upturn_deg.toFixed(0)} len ${l2.length_ratio.toFixed(2)} rr ${l2.radius_ratio.toFixed(2)} tip elev ${l2.elevTip.toFixed(0)}` : 'L2: none'];
    text.forEach((tx, k) => { out += `<text x="${x + 12}" y="${gy + 18 + k * 15}" font-size="${k ? 10.5 : 13}" font-family="-apple-system, Helvetica, sans-serif" fill="#222">${tx.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')}</text>`; });
    x += pw;
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${x}" height="${ph}" viewBox="0 0 ${x} ${ph}"><rect width="100%" height="100%" fill="#eef1ee"/>${out}</svg>`;
}

