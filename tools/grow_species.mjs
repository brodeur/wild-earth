#!/usr/bin/env node
// Grow a tree species through its life by the mechanics of its limbs and write the generator's age classes.
// Step 1 of docs/tree-architecture.md ("Trees grow their age", 2026-11-01). Pure arithmetic, no three.js, as gait.js is.
//
//   ~/.nvm/versions/node/v24.13.0/bin/node tools/grow_species.mjs quercus_lobata [quercus_douglasii ...] [--write] [--svg <dir>]
//        [--grown <dir>] [--ages 10,30,80,200] [--seed 7] [--quiet]
//
//   --write        write the fitted parameters into the record's `variants` (and the base class into the record's own
//                  trunk / levels / crown.envelope / height_m), keeping every hand-set field. Without it: print only.
//   --svg <dir>    one SVG per species: the grown skeleton at each age, side on, with the fitted numbers.
//   --grown <dir>  the grown skeletons as JSON for the lineup page (?grown=1 draws them beside the class trees);
//                  default library/species/grown (git-ignored: regenerated by this tool).
//   --ages         report ages, else the record's growth.classes.
//
// THE LOOP (one pass a year over a skeleton of growth units, each a segment with a length, a base radius, a rest
// orientation relative to its parent and an elastic bend; every lateral starts at the end of the unit that bore it):
//   1. Primary growth. Every live tip extends by the species' height curve for the year (the leader) or by the lateral
//      share of it (laterals), steered from its present direction toward its gravitropic setpoint (Bastien et al. 2013:
//      a shoot's bending is gravity sensing against its own curvature sensing; one number B sets how fast it converges,
//      taken here as the fraction 1 - exp(-1 / B) of the remaining angle per growth unit). Each unit bears a flush of
//      laterals at the architectural model's insertion angle for the next order (Rauh: rhythmic, monopodial, the
//      laterals repeating the trunk), spiralled by the golden angle or set in a whorl (conifers). The leader-to-lateral
//      share follows Palubicki's apical-control weight lambda (0.54 excurrent to 0.46 decurrent) which decays with age
//      for broadleaves and holds for conifers (Wilson 2000; van Rooij et al. 2023); the lateral setpoint steepens as
//      control fades (Rauh branches are orthotropic: freed of the leader they rise and found crowns of their own,
//      Halle, Oldeman and Tomlinson 1978). Shaded tips (Palubicki's shadow propagation over a voxel grid) stop and
//      die; a dead branch thinner than shed_radius_m is shed, a thick one stays as deadwood for a while.
//   2. Thickening by the pipe rule (Shinozaki 1964; Leonardo's exponent 2, measured 1.8-2.3, Eloy 2011; MAppleT
//      fitted 2.49): the trunk at breast height takes the species' dbh for the age and every segment's radius is that
//      times (its share of the live tips)^(1/p), never shrinking. The new ring is the difference.
//   3. Sag. From the tips in, the mass beyond each joint (wood by green density, a leaf load per live tip) and its
//      moment about the joint; the joint bends by M l / (E I), I = pi r^4 / 4 (Jirasek, Prusinkiewicz and Moulia 2000;
//      MAppleT, Costes et al. 2008); the whole subtree follows; two relaxation passes.
//   4. Shape memory. The rest orientation moves toward the loaded one by the new ring's share of the stiffness,
//      1 - (r_old / r_new)^4 (Jirasek et al. 2000 eq. 24; Fournier 1991).
//   5. Reaction wood. Each live segment turns back toward its setpoint by at most 4 dmu dr l / r^2 a year (the curvature
//      a ring of maturation strain dmu on one side of a section of radius r can impose, Almeras and Fournier 2009;
//      tension wood on the upper side in broadleaves, compression wood below in conifers, the same correction here).
//      The correction falls as 1 / r^2 while the load moment grows with the whole reach: thick old limbs lose to gravity
//      and sag, thin young tips win and turn up.
//
// CONSTANTS (starting points; each record's `growth` block can override any of them):
//   E (modulus, green)      oak 8.6 GPa: white oak green, Wood Handbook FPL-GTR-190 table 5-3a (green oaks 6-11 GPa);
//                           ponderosa 6.9 GPa, the same table. MAppleT's 1.1 GPa was fitted for apple (1-7 tested) and
//                           is not used.
//   rho (density, green)    about 1,000 kg/m3 for oaks (van Rooij et al. 2023 take green wood as water; the Wood
//                           Handbook's green white oak weighs about 990); ponderosa 720 (specific gravity 0.38 at
//                           about 90 % moisture).
//   dmu (maturation strain difference across the section)  1.5e-3 (1-2e-3 the range in the design: tension wood
//                           matures at 2,100-5,000 microstrain against 400-700 for normal wood, van Rooij et al. 2023);
//                           conifers 3e-3 (compression wood's strain is compressive, 2-4e-3, against the normal wood's
//                           tensile 0.5e-3, after Thibaut and Gril 2021 as van Rooij et al. use them; not read in full);
//                           over the share of the ring that is reaction wood, half the sine of the angle off the setpoint
//                           (the half ring the 4 dmu dr l / r^2 bound assumes at a right angle; 0.164 at 19 degrees, the
//                           share MAppleT gives a horizontal apple shoot after Almeras 2001).
//   p (pipe exponent)       2.0 (Leonardo; 1.8-2.3 across species, Eloy 2011; MAppleT 2.49).
//   lambda                  0.54 -> 0.46 (Palubicki et al. 2009, the range that turns an excurrent crown decurrent), the
//                           decay time 40 years for broadleaves (DeepTree's oak set has an apical-dominance age factor
//                           0.3 at age 35, Stava et al. 2014, read as the control mostly gone by then), none for conifers.
//   B (Bastien)             3 (0.9-9.3 across eleven angiosperms, Bastien et al. 2013).
//   insertion angles        by model and leaf type: Rauh broadleaf 50, 58, 64 degrees from the parent for orders 1-3;
//                           Rauh conifer 82, 56, 50 (measured for almost no tree; defaults tuned against photographs).
//   laterals per unit       Rauh broadleaf 2, 2, 1, 1 by the bearing order; Rauh conifer 5 (a whorl), 2, 1, 1; orders past
//                           four count as four; growth.epicormic (default 0) lets a limb that loses its tips sprout an
//                           epicormic shoot instead of dying (tried at 0.8 for the oaks: the churn of sprouts against the
//                           tip cap pulled the crown apart, so it is off until the cap is a light budget).
//   creep                   2: the elastic deflection under a load held for years is 1.5-2 times the short-term one
//                           (Wood Handbook FPL-GTR-190 ch. 5, "creep"), so the sag uses E / 2; growth.wood.modulus_effective_gpa
//                           sets the effective modulus outright where the photographs ask for more (branch wood is
//                           juvenile wood with knots, 50-70 % of the clear-specimen modulus; MAppleT fitted 1.1 GPa for
//                           apple limbs, 1-7 tested). growth.trunk_stiffness_factor (default 3) stiffens the trunk alone:
//                           the loop has no eccentric growth or whole-tree righting, which hold a real trunk upright.
//   extension               the leader's by the height curve; the laterals' by the species' crown width for the age (the
//                           Urban Tree Database by age, else Bechtold's largest crown width on the dbh for the age times
//                           growth.open_grown_factor), the outer tips adding what the crown lacks, finer orders 0.9 x per order.
//   shade                   a tip's light falls as exp(-depth / d0) with its depth inside the crown's own surface (the
//                           90th-percentile radius of the live tips by height band and azimuth sector), d0 = 6 % of the height + 0.4 m; a
//                           tip dies when its light is below the shed level for its shade tolerance (intolerant 0.25,
//                           intermediate 0.15, tolerant 0.08 of full) three years running.
// WHAT THE SOURCES DID NOT GIVE: the insertion angles and setpoints (no species), the leaf load per shoot (derived here
// from the Urban Tree Database's leaf-area equation and leaf mass per area for valley oak; defaults for the rest), the
// moduli of the California oaks (white oak stands in), the lateral share and the shade thresholds (tuned).
